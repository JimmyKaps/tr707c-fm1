"""Writes firmware/gen/tr707c_tables.h: the constants TR-707C needs, so the chip (no FPU) never computes an exp or a pow.
   python3 tools/gen_tr707c_tables.py"""
import math
from pathlib import Path
FS = 44100
# name, f0 Hz, sweep Hz, pitch-env shift (per 4 frames), metal(0/1), osc2 ratio Q8, noise 0..255, noise hp Q8, decay ms
V = [
 ("BD",   50, 170, 9, 0,   0,  10,  20,  380),
 ("SD",  185,  60, 8, 0,   0, 170,  90,  190),
 ("LT",   95,  80, 9, 0,   0,   0,   0,  330),
 ("MT",  140,  90, 9, 0,   0,   0,   0,  290),
 ("HT",  200, 110, 9, 0,   0,   0,   0,  250),
 ("RIM",1700,   0, 6, 0,   0,  60, 160,   45),
 ("CLP",   0,   0, 0, 0,   0, 255, 110,  260),
 ("COW", 540,   0, 0, 1, 380,   0,   0,  230),
 ("CH",  330,   0, 0, 1, 640, 200, 230,   60),
 ("OH",  330,   0, 0, 1, 640, 200, 230,  420),
 ("CR",  400,   0, 0, 1, 590, 220, 200, 1300),
 ("RD",  450,   0, 0, 1, 610, 150, 220,  750),
 ("TB",    0,   0, 0, 0,   0, 255, 200,  110),
]
inc = lambda hz: round(hz * 2**32 / FS)
o = ["/* SPDX-License-Identifier: GPL-3.0-only */",
     "/* generated by tools/gen_tr707c_tables.py: do not edit */",
     "typedef struct { uint32_t inc0, sweep; uint16_t ratio; uint8_t pdec, metal, noise, hp; } tr_vdef_t;",
     "static const tr_vdef_t TR_VDEF[13] = {"]
for n, f0, sw, pd, me, ra, no, hp, ms in V:
    o.append(f"    {{{inc(f0)}u, {inc(sw)}u, {ra}, {pd}, {me}, {no}, {hp}}},   /* {n} */")
o.append("};")
o.append("/* amplitude multiplier per 4 frames, Q24, for decay CC 0..127 (x0.25 .. x2.5 of the voice's decay to -60 dB) */")
o.append("static const uint32_t TR_DEC4[13][128] = {")
for n, f0, sw, pd, me, ra, no, hp, ms in V:
    row = []
    for p in range(128):
        t = ms / 1000 * (0.25 + 2.25 * p / 127)
        m = math.exp(-6.9078 * 4 / (t * FS))
        row.append(min(round(m * 2**24), 2**24 - 1))
    o.append("    {" + ",".join(map(str, row)) + "},   /* " + n + " */")
o.append("};")
o.append("/* tune CC 0..127 -> pitch factor Q16 (64 = 1.0, +-1 octave) */")
o.append("static const uint32_t TR_TUNE[128] = {" + ",".join(str(round(65536 * 2 ** ((p - 64) / 64))) for p in range(128)) + "};")
o.append("/* the same factor as a noise filter scale for the voices without pitch (clap, tambourine) */")
Path("firmware/gen/tr707c_tables.h").write_text("\n".join(o) + "\n")
print("firmware/gen/tr707c_tables.h", sum(len(x) for x in o), "bytes")
